export const BUSINESS_NAME = 'Bunny Momos, Bardhaman';

// The first tab of every workbook: what this is, for when, and what each tab means.
export function readmeSheet(ctx: ReportContext, reportName: string, tabs: [string, string][], notes: string[] = []): SheetSpec {
  const p = ctx.period;
  const rows: CellValue[][] = [
    ['Business', BUSINESS_NAME],
    ['Report', reportName],
    ['Period', p.label],
    ['Dates', `${p.start} to ${p.end}`],
    ['Data up to', p.partial ? `${p.dataEnd} (the period is still running)` : p.end],
    ['Covers', scopeLabel(ctx)],
    ['Generated at', ctx.generatedAt],
    ['Generated by', ctx.generatedBy],
    ['Amounts', 'Indian rupees. Not GST-registered, so amounts include no input GST to claim.'],
    ['Dates', 'Calendar dates in India time (IST), written YYYY-MM-DD.'],
    ['', ''],
    ['Tab', 'What it shows'],
    ...tabs.map(([tab, what]) => [tab, what] as CellValue[]),
  ];
  if (notes.length) rows.push(['', ''], ['Notes', ''], ...notes.map((n) => ['', n] as CellValue[]));
  return { name: 'README', title: `${BUSINESS_NAME} - ${reportName}`, columns: [{ header: 'Item', width: 22 }, { header: 'Details', width: 110 }], rows };
}

export const PNL_DEFINITIONS = [
  'Sales: counter sales are what the store counted at closing (cash + Paytm/UPI); Zomato/Swiggy sales are from the billing system.',
  'Food and packaging: purchases logged as inventory. Bulk box/tray orders are counted over the 120 days they last.',
  'Commission: from Zomato/Swiggy settlement files, without the 5% GST they collect and pay for us. Days not settled yet are estimated at the last 60 days\' rate.',
  'Staff: salaries in the month they cover (a September salary paid on 5 October is September\'s), plus personal expenses deducted from salary.',
  'Equipment, furniture, electrical work and the scooter are counted evenly over 36 months; the yearly POS subscription over 12. Loan EMIs are never a cost.',
  'Interest: on owner/investor loans, per day at the agreed monthly rate. Approved cash shortages are a loss.',
];

export function storeVsProductionSheet(ctx: ReportContext, storeP: PnlBreakdown, prodP: PnlBreakdown): SheetSpec {
  const lines: [string, (p: PnlBreakdown) => number][] = [
    ['Sales', (p) => p.revenue],
    ['Food (ingredients)', (p) => p.food],
    ['Packaging', (p) => p.packaging],
    ['Zomato/Swiggy commission and ads', (p) => p.commission + p.platformAds],
    ['Marketing', (p) => p.marketing],
    ['Staff salaries', (p) => p.staff],
    ['Rent, electricity, internet', (p) => p.occupancy],
    ['Other running costs', (p) => p.otherOpex],
    ['Equipment and scooter (spread)', (p) => p.depreciation],
    ['Loan interest and cash shortages', (p) => p.interest + p.shortages],
    ['Total costs', (p) => pnlCosts(p)],
    ['Net profit', (p) => p.netProfit],
  ];
  return {
    name: 'Store vs production',
    title: `Store and production house costs - ${ctx.period.label}`,
    notes: ['One ₹20,000 rent covers both places; it shows on whichever side it was logged against. Sales, online costs, loan interest and cash shortages belong to the store.'],
    columns: [{ header: 'Line', width: 36 }, { header: 'Store', format: 'inr' }, { header: 'Production house', format: 'inr' }, { header: 'Together', format: 'inr' }, { header: 'Production share', format: 'pct' }],
    rows: lines.map(([label, f]) => {
      const s = f(storeP), h = f(prodP), t = s + h;
      return [label, s, h, t, Math.abs(t) > 0.005 && label !== 'Net profit' && label !== 'Sales' ? h / t : null];
    }),
  };
}

export function pnlTableHtml(rows: { label: string; strong?: boolean; cells: string[] }[], headers: string[]): string {
  return `<div class="tbl"><table><thead><tr>${headers.map((h, i) => `<th${i ? ' class="num"' : ''}>${escapeHtml(h)}</th>`).join('')}</tr></thead><tbody>${
    rows.map((r) => `<tr${r.strong ? ' class="strong"' : ''}><td>${escapeHtml(r.label)}</td>${r.cells.map((c) => `<td class="num">${escapeHtml(c)}</td>`).join('')}</tr>`).join('')
  }</tbody></table></div>`;
}

export function pnlHtml(current: PnlBreakdown, previous: PnlBreakdown | null): string {
  const rows = pnlRowsFor(previous ? [current, previous] : [current]).map((r) => ({
    label: r.label,
    strong: r.strong,
    cells: [
      inr(r.value(current)),
      current.revenue > 0 ? pctText(r.value(current) / current.revenue) : '',
      ...(previous ? [inr(r.value(previous))] : []),
    ],
  }));
  return pnlTableHtml(rows, ['Line', 'Amount', '% of sales', ...(previous ? ['Previous'] : [])]);
}

const change = (now: number, before: number) =>
  Math.abs(before) < 0.005 ? '' : `${now >= before ? '+' : ''}${(((now - before) / Math.abs(before)) * 100).toFixed(1)}% vs previous`;

// ---------- Quick export: every ledger for the period ----------

export function buildQuickExport(ctx: ReportContext) {
  const prev = previousPeriod(ctx.period, ctx.today);
  const current = pnlFor(ctx, ctx.period.start, ctx.period.dataEnd);
  const previous = pnlFor(ctx, prev.start, prev.dataEnd);
  const summary = pnlSummarySheet(ctx, current, previous, prev.label);
  const split = ctx.scope === 'combined'
    ? storeVsProductionSheet(ctx, pnlFor(ctx, ctx.period.start, ctx.period.dataEnd, 'store'), pnlFor(ctx, ctx.period.start, ctx.period.dataEnd, 'production'))
    : null;
  const sales = salesDayBook(ctx);
  const purchases = purchasesRegister(ctx);
  const expenses = expensesRegister(ctx);
  const payroll = payrollRegister(ctx);
  const loans = loansSheet(ctx);
  const sheets: SheetSpec[] = [
    readmeSheet(ctx, 'All records', [
      ['Profit and loss', 'The period\'s profit, line by line, with % of sales and the previous period'],
      ...(split ? [['Store vs production', 'Costs of the store and the production house side by side'] as [string, string]] : []),
      ['Sales day book', 'Every day\'s sales, cash count and approval'],
      ['Purchases register', 'Every inventory purchase with a price check'],
      ['Expenses register', 'Running expenses and fixed costs, with the P&L line each lands on'],
      ['Payroll register', 'Salary payouts (employee code and name only)'],
      ['Salary advances', 'Advances asked for in the period'],
      ['Loans', 'Owner/investor loans outstanding at the end of the period'],
      ['Production', 'Daily production log'],
      ['Items sold', 'Momo pieces sold by type'],
      ['Staff', 'Who works here (no phone numbers or ID details)'],
    ], PNL_DEFINITIONS),
    summary,
    ...(split ? [split] : []),
    sales, purchases, expenses, payroll, salaryAdvancesSheet(ctx), loans, productionSheet(ctx), itemsSoldSheet(ctx), staffSheet(ctx),
  ];

  const html = printableDocument({
    title: `${BUSINESS_NAME} - business report`,
    subtitle: `${ctx.period.label}${ctx.period.partial ? ` (up to ${prettyDate(ctx.period.dataEnd)})` : ''}`,
    meta: [scopeLabel(ctx), `Generated ${ctx.generatedAt} by ${ctx.generatedBy}`],
    sections: [
      {
        heading: 'At a glance',
        html: cardsHtml([
          { label: 'Sales', value: inr(current.revenue), sub: change(current.revenue, previous.revenue) },
          { label: 'Costs', value: inr(pnlCosts(current)), sub: change(pnlCosts(current), pnlCosts(previous)) },
          { label: 'Net profit', value: inr(current.netProfit), sub: change(current.netProfit, previous.netProfit) },
          { label: 'Net margin', value: current.revenue > 0 ? pctText(current.netProfit / current.revenue) : '-', sub: `Previous: ${prev.label}` },
        ]),
      },
      { heading: 'Profit and loss', intro: summary.notes?.join(' '), html: pnlHtml(current, previous) },
      ...(split ? [{ heading: 'Store vs production house', intro: split.notes?.join(' '), html: sheetTable(split) }] : []),
      { heading: 'Sales day book', html: sheetTable({ ...sales, columns: sales.columns.slice(0, 15), rows: sales.rows.map((r) => r.slice(0, 15)) }, { maxRows: 93 }), pageBreakBefore: true },
      { heading: 'Purchases', html: sheetTable({ ...purchases, columns: purchases.columns.slice(0, 9), rows: purchases.rows.map((r) => r.slice(0, 9)) }, { maxRows: 150 }), pageBreakBefore: true },
      { heading: 'Expenses', html: sheetTable({ ...expenses, columns: expenses.columns.slice(0, 8), rows: expenses.rows.map((r) => r.slice(0, 8)) }, { maxRows: 150 }), pageBreakBefore: true },
      { heading: 'Payroll', html: sheetTable({ ...payroll, columns: payroll.columns.slice(0, 11), rows: payroll.rows.map((r) => r.slice(0, 11)) }, { maxRows: 150 }) },
      { heading: 'Loans', intro: loans.notes?.join(' '), html: sheetTable({ ...loans, columns: loans.columns.slice(0, 9), rows: loans.rows.map((r) => r.slice(0, 9)) }) },
    ],
    footnotes: PNL_DEFINITIONS,
    landscape: true,
  });
  return { sheets, html, current, previous, previousLabel: prev.label };
}

// ---------- Pack A: auditor workbook ----------

export function buildAuditorWorkbook(ctx: ReportContext): SheetSpec[] {
  const prev = previousPeriod(ctx.period, ctx.today);
  const current = pnlFor(ctx, ctx.period.start, ctx.period.dataEnd);
  const previous = pnlFor(ctx, prev.start, prev.dataEnd);
  const exceptions = exceptionsSheet(ctx);
  return [
    readmeSheet(ctx, 'Auditor workbook', [
      ['Profit and loss', 'Profit for the period, line by line - the same figures the Analytics screen shows'],
      ['Sales day book', 'One row per store per day: POS sales (offline/online), cash and Paytm counted, till short/over with its reason, whether a person counted the cash, approval, who entered and approved it'],
      ['Purchases register', 'Every inventory purchase: where, category, item, qty, unit, unit cost, total, how it was paid, price-check flag, who entered it, record id'],
      ['Expenses register', 'Running expenses and fixed costs (rent, electricity, internet) with the P&L line each lands on'],
      ['Payroll register', 'Salary payouts by employee code: month covered, date paid, gross, advance deducted, net, paid from'],
      ['Store cash book', 'Store till each day: opening, cash in, cash out, expected, counted, difference'],
      ['Production cash book', 'Production house cash each day: opening (incl. the store cash handed over), top-ups, spending, expected, counted, difference'],
      ['Paytm ledger', 'Every movement of the Paytm/UPI balance with the running balance'],
      ['Aggregator reconciliation', 'Each Zomato/Swiggy settlement: order dates, gross, deductions, GST, ads, discounts, net payout, check'],
      ['Exceptions', 'Days without a real cash count, unexplained till gaps, pending approvals, possible duplicates, price flags, missing settlements, cash payments over ₹10,000 to one payee in a day (Income Tax s.40A(3))'],
    ], [
      ...PNL_DEFINITIONS,
      'Record id is the app\'s own id for the entry - quote it when asking about a row.',
      'Cash counted by a person: the POS sync creates each day\'s record with a 0 cash count; only a count a person saved is treated as counted.',
      'No phone numbers, Aadhaar or bank details are included anywhere in this workbook.',
      `Exceptions found: ${exceptions.rows.length}.`,
    ]),
    pnlSummarySheet(ctx, current, previous, prev.label),
    salesDayBook(ctx),
    purchasesRegister(ctx),
    expensesRegister(ctx),
    payrollRegister(ctx),
    storeCashBook(ctx),
    productionCashBook(ctx),
    paytmLedgerSheet(ctx),
    aggregatorRecon(ctx),
    exceptions,
  ];
}
